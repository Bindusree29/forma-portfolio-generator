require('dotenv').config();
const path=require('node:path');
const express=require('express');
const helmet=require('helmet');
const rateLimit=require('express-rate-limit');
const portfolios=require('./routes/portfolios');
const app=express();
const port=Number(process.env.PORT)||3000;
app.disable('x-powered-by');
app.use(helmet({contentSecurityPolicy:{directives:{defaultSrc:["'self'"],scriptSrc:["'self'"],styleSrc:["'self'","'unsafe-inline'"],imgSrc:["'self'","data:"],connectSrc:["'self'"],objectSrc:["'none'"],baseUri:["'self'"]}}}));
app.use(express.json({limit:'32kb'}));
app.use('/api',rateLimit({windowMs:15*60*1000,limit:100,standardHeaders:'draft-8',legacyHeaders:false}));
app.get('/api/health',(_req,res)=>res.json({status:'ok'}));
app.use('/api/portfolios',portfolios);
app.use(express.static(path.join(__dirname,'..','frontend')));
app.get('/p/:slug',(_req,res)=>res.sendFile(path.join(__dirname,'..','frontend','index.html')));
app.use((req,res)=>req.path.startsWith('/api/')?res.status(404).json({error:'API endpoint not found.'}):res.status(404).send('Page not found.'));
app.use((error,_req,res,_next)=>{console.error(error.message);if(!res.headersSent)res.status(error.status||500).json({error:error.status===413?'Request is too large.':'Unexpected server error.'})});
app.listen(port,()=>console.log('Forma Studio running at http://localhost:'+port));
